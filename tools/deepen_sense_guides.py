ANCHOR_RE = re.compile(
    r'(\n {10}<div class="article-card">\n {12}<h2>次に読みたい関連ガイド</h2>)')


def card(kicker, h2, items):
    lis = "\n".join(
        f'              <li><strong>{a}</strong><span>{b}</span></li>'
        for a, b in items)
    return ('          <div class="article-card">\n'
            f'            <p class="article-kicker">{kicker}</p>\n'
            f'            <h2>{h2}</h2>\n'
            '            <ul class="article-list">\n'
            f'{lis}\n'
            '            </ul>\n'
            '          </div>\n')


def main():
    n = 0
    for slug, (train, fail) in DATA.items():
        path = os.path.join(ROOT, f"{slug}.html")
        s = open(path, encoding="utf-8").read()
        if "ありがちな失敗" in s:
            print("  skip (already):", slug)
            continue
        m = ANCHOR_RE.search(s)
        if not m:
            print("  WARN no anchor:", slug)
            continue
        block = card("TRAINING", "この力の鍛え方", train) + \
            card("PITFALLS", "ありがちな失敗", fail)
        s = s[:m.start()] + "\n" + block + s[m.start() + 1:]
        open(path, "w", encoding="utf-8").write(s)
        print("  deepened:", slug)
        n += 1
    print("sense guides deepened:", n)


if __name__ == "__main__":
    main()
