def main():
    path = 'device-zukan.html'
    s = open(path, encoding='utf-8').read()
    m = re.search(r'(      var DATA = )(\[.*?\])(;\n)', s, re.S)
    if not m:
        raise SystemExit('DATA の抽出に失敗')
    data = json.loads(m.group(2))

    known = {d['name'] for d in data}
    unknown = [k for k in SPECS if k not in known]
    if unknown:
        raise SystemExit(f'DATAに存在しない製品名: {unknown}')

    filled = 0
    for d in data:
        if d.get('specs'):
            continue
        spec = SPECS.get(d['name'])
        if spec:
            d['specs'] = spec
            filled += 1

    new_json = json.dumps(data, ensure_ascii=False)
    s = s[:m.start()] + m.group(1) + new_json + m.group(3) + s[m.end():]
    open(path, 'w', encoding='utf-8').write(s)

    total = len(data)
    have = sum(1 for d in data if d.get('specs'))
    print(f'スペック補完: {filled}件 / 収録率 {have}/{total}')
    rest = [d['name'] for d in data if not d.get('specs')]
    if rest:
        print('未収録:', rest)


main()
