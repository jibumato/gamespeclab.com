CARD = re.compile(
    r'<div class="article-card">\s*<p class="article-kicker">TYPE OVERVIEW</p>.*?</div>',
    re.S)


def new_card(h2, paras):
    ps = "\n".join(f"            <p>{p}</p>" for p in paras)
    return ('<div class="article-card type-overview">\n'
            '            <p class="article-kicker">TYPE OVERVIEW</p>\n'
            f'            <h2>{h2}</h2>\n'
            f'{ps}\n'
            '          </div>')


n = 0
for code, (h2, paras) in DATA.items():
    path = os.path.join(ROOT, f"gamer-mbti-{code}.html")
    s = open(path, encoding="utf-8").read()
    s2, c = CARD.subn(new_card(h2, paras), s, count=1)
    if c != 1:
        print("WARN no match:", code)
        continue
    open(path, "w", encoding="utf-8").write(s2)
    n += 1
print("rewritten TYPE OVERVIEW:", n, "pages")
